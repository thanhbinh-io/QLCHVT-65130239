CREATE DATABASE QUANLYVATTUDIENNUOC;
GO
USE QUANLYVATTUDIENNUOC;
GO

-- 2. TẠO BẢNG NHANVIEN (Giữ nguyên)
CREATE TABLE NHANVIEN (
    MANV CHAR(5) PRIMARY KEY,
    TENNV NVARCHAR(40) NOT NULL,
    DIACHI NVARCHAR(100),
    SDT CHAR(10) NOT NULL,
    NGAYSINH SMALLDATETIME
);

-- 3. TẠO BẢNG KHACHHANG (Đã điều chỉnh độ dài DIACHI)
CREATE TABLE KHACHHANG (
    MAKH CHAR(5) PRIMARY KEY,
    TENKH NVARCHAR(40) NOT NULL,
    DIACHI NVARCHAR(100),
    SDT CHAR(10) NOT NULL,
    NGAYDK SMALLDATETIME NOT NULL,
    NGAYSINH SMALLDATETIME,
    DOANHSO MONEY NOT NULL,
    MANV CHAR(5)
);

-- 4. TẠO BẢNG NHOMSANPHAM (MỚI - Phân loại: Ống, Ốc vít, Dụng cụ...)
CREATE TABLE NHOMSANPHAM (
    MANHOM CHAR(5) PRIMARY KEY,
    TENNHOM NVARCHAR(50) NOT NULL
);

-- 5. TẠO BẢNG SANPHAM (ĐÃ TÙY CHỈNH CHO VẬT TƯ)
CREATE TABLE SANPHAM (
    MASP CHAR(10) PRIMARY KEY, -- Mã sản phẩm chi tiết hơn
    TENSP NVARCHAR(100) NOT NULL,
    MANHOM CHAR(5) NOT NULL,    -- Khóa ngoại đến NHOMSANPHAM
    DONVITINH NVARCHAR(20) NOT NULL, -- Ví dụ: Mét, Cuộn, Cái, Kg
    GIANHAP MONEY NOT NULL,
    GIASP MONEY NOT NULL,
    SOLUONGTON INT NOT NULL DEFAULT 0, -- Cột quản lý tồn kho trực tiếp
    MANV CHAR(5)
);

-- 6. TẠO BẢNG HOADON
CREATE TABLE HOADON (
    MAHD CHAR(5) PRIMARY KEY, -- Tăng độ dài MAHD từ 3 lên 5
    MAKH CHAR(5) NOT NULL,
    MANV CHAR(5) NOT NULL,
    NGHD SMALLDATETIME NOT NULL,
    TRIGIA MONEY NOT NULL
);

-- 7. TẠO BẢNG CTHD (Chi Tiết Hóa Đơn)
CREATE TABLE CTHD (
    MAHD CHAR(5),
    MASP CHAR(10),
    SOLUONG SMALLINT NOT NULL,
    CONSTRAINT PK_CTHD PRIMARY KEY (MAHD, MASP)
);

-- 8. TẠO BẢNG PHIEUNHAP
CREATE TABLE PHIEUNHAP (
    MAPN CHAR(5) PRIMARY KEY,
    NGAYNHAP SMALLDATETIME NOT NULL,
    MANV CHAR(5) NOT NULL
);

-- 9. TẠO BẢNG CTPN (Chi Tiết Phiếu Nhập)
CREATE TABLE CTPN (
    MAPN CHAR(5),
    MASP CHAR(10),
    SOLUONG SMALLINT NOT NULL,
    CONSTRAINT PK_CTPN PRIMARY KEY (MAPN, MASP)
);


---------------------------------------------
--- THIẾT LẬP CÁC KHÓA NGOẠI (FOREIGN KEYS)
---------------------------------------------

-- 10. Khóa ngoại cho KHACHHANG
ALTER TABLE KHACHHANG ADD CONSTRAINT FK_KH_NV FOREIGN KEY(MANV) REFERENCES NHANVIEN(MANV);

-- 11. Khóa ngoại cho NHOMSANPHAM (Sản phẩm thuộc nhóm)
ALTER TABLE SANPHAM ADD CONSTRAINT FK_SP_NHOM FOREIGN KEY(MANHOM) REFERENCES NHOMSANPHAM(MANHOM);

-- 12. Khóa ngoại cho SANPHAM (Sản phẩm do nhân viên quản lý)
ALTER TABLE SANPHAM ADD CONSTRAINT FK_SP_NV FOREIGN KEY(MANV) REFERENCES NHANVIEN(MANV);

-- 13. Khóa ngoại cho HOADON
ALTER TABLE HOADON ADD CONSTRAINT FK_HD_NV FOREIGN KEY(MANV) REFERENCES NHANVIEN(MANV);
ALTER TABLE HOADON ADD CONSTRAINT FK_HD_KH FOREIGN KEY(MAKH) REFERENCES KHACHHANG(MAKH);

-- 14. Khóa ngoại cho CTHD
ALTER TABLE CTHD ADD CONSTRAINT FK_CTHD_HD FOREIGN KEY(MAHD) REFERENCES HOADON(MAHD);
ALTER TABLE CTHD ADD CONSTRAINT FK_CTHD_SP FOREIGN KEY(MASP) REFERENCES SANPHAM(MASP);

-- 15. Khóa ngoại cho PHIEUNHAP
ALTER TABLE PHIEUNHAP ADD CONSTRAINT FK_PN_NV FOREIGN KEY(MANV) REFERENCES NHANVIEN(MANV);

-- 16. Khóa ngoại cho CTPN
ALTER TABLE CTPN ADD CONSTRAINT FK_CTPN_PN FOREIGN KEY(MAPN) REFERENCES PHIEUNHAP(MAPN);
ALTER TABLE CTPN ADD CONSTRAINT FK_CTPN_SP FOREIGN KEY(MASP) REFERENCES SANPHAM(MASP);